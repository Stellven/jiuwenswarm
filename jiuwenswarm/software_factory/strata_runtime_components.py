"""Source components of the pinned STRATA checkout, grouped by runtime work.

Grouping describes the upstream call paths. It does not schedule the functions
or certify that a model, a backend, or an optional branch ran.
"""
from __future__ import annotations


def _part(identity, name, path, anchor, symbol, inputs, outputs, when=None):
    part = {
        'id': identity, 'name': name, 'path': path, 'anchor': anchor, 'symbol': symbol,
        'input': inputs, 'output': outputs,
    }
    if when:
        part['when'] = when
    if path.endswith('.py'):
        part['language'] = 'python'
    return part


