"""Authoring tools and the immutable manifest (PAS-M1-001 B02; PRD SL-2; IF-001 "Authoring").

An agent builds an experiment in a draft workspace: geometry and collision
assets, model files (MJCF, optionally templated with ${name}), the procedure,
interventions, measurements, observations and component code at declared
extension points. `bind` copies every artifact into content-addressed blobs and
writes a manifest listing each path and SHA-256, bound to exactly one
experiment. Identical content gives the identical manifest and experiment IDs.
"""
from __future__ import annotations

import ast
import base64
import json
import math
import re
from pathlib import Path, PurePosixPath
from typing import Any

from simlab.contracts import SCHEMA_VERSION, SimlabError, canonical, sha256_hex
from simlab.store import Store, new_id, now

EXTENSION_POINTS: dict[str, dict[str, Any]] = {
    "scene": {"kinds": {"model_file"}, "entry": None,
              "doc": "MJCF model file for the arm's apparatus (may use ${param} placeholders)"},
    "controller": {"kinds": {"component"}, "entry": "control",
                   "doc": "control(obs, params, ctx) -> list[float] | dict(ctrl=...); called every control period"},
    "measurement": {"kinds": {"component"}, "entry": "measure",
                    "doc": "measure(traces, params) -> float; trial-scope custom measurement"},
}
HEADER_FIELDS = {"objective", "objective_kind", "declared_stand_ins", "protocol_items", "sources", "feasibility", "engines",
                 "resolved_configuration", "arms", "design", "checks", "predicates", "thresholds", "limits", "deviations",
                 "parent", "probes", "trace_signals", "measurements", "procedure"}
PATH_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.\-]*(/[A-Za-z0-9_][A-Za-z0-9_.\-]*)*$")
MAX_ARTIFACT = 32 * 2**20


def check_path(path: str) -> str:
    if not isinstance(path, str) or not PATH_RE.match(path) or ".." in PurePosixPath(path).parts or len(path) > 200:
        raise SimlabError("E_INVALID_INPUT", f"artifact path {path!r} must be a relative path of letters, digits, '_', '-', '.'", "/path")
    return path


# ------------------------------------------------------------------ geometry generators (OBJ text)
def _obj(vertices: list[tuple[float, float, float]], faces: list[tuple[int, ...]]) -> str:
    lines = ["# generated by simlab geometry_put"]
    lines += [f"v {x:.9g} {y:.9g} {z:.9g}" for x, y, z in vertices]
    lines += ["f " + " ".join(str(i + 1) for i in f) for f in faces]
    return "\n".join(lines) + "\n"


def primitive_mesh(spec: dict) -> str:
    shape = spec.get("shape")
    if shape == "box":
        hx, hy, hz = (float(v) for v in spec["half_size"])
        v = [(sx * hx, sy * hy, sz * hz) for sz in (-1, 1) for sy in (-1, 1) for sx in (-1, 1)]
        f = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        return _obj(v, f)
    if shape == "cylinder":
        r, hh, n = float(spec["radius"]), float(spec["half_height"]), int(spec.get("segments", 32))
        if n < 3:
            raise SimlabError("E_INVALID_INPUT", "cylinder needs at least 3 segments", "/primitive/segments")
        v = [(r * math.cos(2 * math.pi * i / n), r * math.sin(2 * math.pi * i / n), z) for z in (-hh, hh) for i in range(n)]
        f = [tuple(range(n - 1, -1, -1)), tuple(range(n, 2 * n))]
        f += [(i, (i + 1) % n, n + (i + 1) % n, n + i) for i in range(n)]
        return _obj(v, f)
    if shape == "sphere":
        r, n = float(spec["radius"]), int(spec.get("segments", 16))
        rings = max(3, n // 2)
        v = [(0.0, 0.0, -r)]
        for j in range(1, rings):
            phi = -math.pi / 2 + math.pi * j / rings
            for i in range(n):
                th = 2 * math.pi * i / n
                v.append((r * math.cos(phi) * math.cos(th), r * math.cos(phi) * math.sin(th), r * math.sin(phi)))
        v.append((0.0, 0.0, r))
        top = len(v) - 1
        f = [(0, 1 + (i + 1) % n, 1 + i) for i in range(n)]
        for j in range(rings - 2):
            a, b = 1 + j * n, 1 + (j + 1) * n
            f += [(a + i, a + (i + 1) % n, b + (i + 1) % n, b + i) for i in range(n)]
        last = 1 + (rings - 2) * n
        f += [(last + i, last + (i + 1) % n, top) for i in range(n)]
        return _obj(v, f)
    raise SimlabError("E_INVALID_INPUT", f"unknown primitive shape {shape!r} (box, cylinder, sphere)", "/primitive/shape")


def obj_vertices(text: str) -> list[tuple[float, float, float]]:
    out = []
    for line in text.splitlines():
        if line.startswith("v "):
            x, y, z = (float(t) for t in line.split()[1:4])
            out.append((x, y, z))
    return out


# ------------------------------------------------------------------ the authoring service
class Authoring:
    def __init__(self, store: Store):
        self.store = store

    # drafts --------------------------------------------------------
    def draft_create(self, header: dict | None = None, parent: dict | None = None) -> dict:
        header = dict(header or {})
        unknown = set(header) - HEADER_FIELDS
        if unknown:
            raise SimlabError("E_INVALID_INPUT", f"unknown draft header fields: {sorted(unknown)}", "/header")
        draft_id = new_id("draft")
        t = now()
        with self.store.tx() as db:
            db.execute("INSERT INTO drafts(draft_id,header,parent,created_at,updated_at) VALUES(?,?,?,?,?)",
                       (draft_id, json.dumps(header), json.dumps(parent) if parent else None, t, t))
        (self.store.drafts_dir / draft_id).mkdir(parents=True, exist_ok=True)
        return {"draft_id": draft_id}

    def _draft(self, draft_id: str, *, writable: bool = True):
        row = self.store.q1("SELECT * FROM drafts WHERE draft_id=?", (draft_id,))
        if row is None:
            raise SimlabError("E_UNKNOWN_DRAFT", f"no draft {draft_id}", "/draft_id")
        if writable and row["bound_manifest_id"]:
            raise SimlabError("E_BOUND", f"draft {draft_id} is bound to manifest {row['bound_manifest_id']}; start a new draft or branch",
                              "/draft_id")
        return row

    def _put(self, draft_id: str, path: str, kind: str, data: bytes, extension_point: str | None = None) -> dict:
        self._draft(draft_id)
        check_path(path)
        if len(data) > MAX_ARTIFACT:
            raise SimlabError("E_INVALID_INPUT", f"artifact {path} exceeds {MAX_ARTIFACT} bytes", "/content")
        f = self.store.drafts_dir / draft_id / path
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(data)
        sha = sha256_hex(data)
        with self.store.tx() as db:
            db.execute("INSERT OR REPLACE INTO draft_artifacts(draft_id,path,kind,extension_point,sha256,bytes,updated_at)"
                       " VALUES(?,?,?,?,?,?,?)", (draft_id, path, kind, extension_point, sha, len(data), now()))
            db.execute("UPDATE drafts SET updated_at=? WHERE draft_id=?", (now(), draft_id))
        return {"draft_id": draft_id, "path": path, "kind": kind, "sha256": sha, "bytes": len(data)}

    @staticmethod
    def _content(content: str | None, content_b64: str | None) -> bytes:
        if (content is None) == (content_b64 is None):
            raise SimlabError("E_INVALID_INPUT", "give exactly one of content or content_b64", "/content")
        if content is not None:
            return content.encode()
        try:
            return base64.b64decode(content_b64, validate=True)
        except Exception as exc:
            raise SimlabError("E_INVALID_INPUT", f"content_b64 is not base64: {exc}", "/content_b64") from None

    def _file(self, draft_id: str, path: str) -> bytes:
        f = self.store.drafts_dir / draft_id / check_path(path)
        if not f.is_file():
            raise SimlabError("E_SEMANTIC_UNKNOWN_REF", f"draft {draft_id} has no artifact {path}", "/path")
        return f.read_bytes()

    # artifact categories -------------------------------------------
    def geometry_put(self, draft_id: str, path: str, content: str | None = None, content_b64: str | None = None,
                     primitive: dict | None = None) -> dict:
        if primitive is not None:
            if content is not None or content_b64 is not None:
                raise SimlabError("E_INVALID_INPUT", "give content, content_b64 or primitive, not several", "/primitive")
            data = primitive_mesh(primitive).encode()
        else:
            data = self._content(content, content_b64)
        return self._put(draft_id, path, "geometry", data)

    def collision_put(self, draft_id: str, path: str, content: str | None = None, content_b64: str | None = None,
                      primitive: dict | None = None, from_geometry: dict | None = None) -> dict:
        if from_geometry is not None:
            src = self._file(draft_id, from_geometry["path"])
            method = from_geometry.get("method", "copy")
            if method == "copy":
                data = src
            elif method == "bounding_box":
                vs = obj_vertices(src.decode())
                if not vs:
                    raise SimlabError("E_INVALID_INPUT", "bounding_box needs an OBJ geometry with vertices", "/from_geometry/path")
                lo = [min(v[i] for v in vs) for i in range(3)]
                hi = [max(v[i] for v in vs) for i in range(3)]
                c = [(a + b) / 2 for a, b in zip(lo, hi)]
                half = [(b - a) / 2 for a, b in zip(lo, hi)]
                box = obj_vertices(primitive_mesh({"shape": "box", "half_size": half}))
                text = primitive_mesh({"shape": "box", "half_size": half})
                lines = [ln for ln in text.splitlines() if not ln.startswith("v ")]
                vlines = [f"v {x + c[0]:.9g} {y + c[1]:.9g} {z + c[2]:.9g}" for x, y, z in box]
                data = ("\n".join([lines[0], *vlines, *lines[1:]]) + "\n").encode()
            else:
                raise SimlabError("E_INVALID_INPUT", f"unknown method {method!r} (copy, bounding_box)", "/from_geometry/method")
        elif primitive is not None:
            data = primitive_mesh(primitive).encode()
        else:
            data = self._content(content, content_b64)
        return self._put(draft_id, path, "collision", data)

    def model_file_put(self, draft_id: str, path: str, content: str) -> dict:
        return self._put(draft_id, path, "model_file", content.encode())

    def procedure_put(self, draft_id: str, procedure: dict) -> dict:
        return self._put(draft_id, "procedure.json", "procedure", canonical(procedure))

    def intervention_put(self, draft_id: str, intervention: dict) -> dict:
        iid = intervention.get("intervention_id")
        if not isinstance(iid, str) or not iid:
            raise SimlabError("E_INVALID_INPUT", "intervention_id is required", "/intervention/intervention_id")
        return self._put(draft_id, f"interventions/{check_path(iid)}.json", "intervention", canonical(intervention))

    def measurement_put(self, draft_id: str, measurement: dict) -> dict:
        mid = measurement.get("measurement_id")
        if not isinstance(mid, str) or not mid:
            raise SimlabError("E_INVALID_INPUT", "measurement_id is required", "/measurement/measurement_id")
        return self._put(draft_id, f"measurements/{check_path(mid)}.json", "measurement", canonical(measurement))

    def observation_put(self, draft_id: str, observation: dict, probe: bool = False) -> dict:
        sig = observation.get("signal")
        if not isinstance(sig, str) or not sig:
            raise SimlabError("E_INVALID_INPUT", "signal is required", "/observation/signal")
        name = "".join(c if c.isalnum() or c in "-_." else "_" for c in sig)
        folder = "probes" if probe else "observations"
        return self._put(draft_id, f"{folder}/{name}.json", "observation", canonical(observation))

    def component_put(self, draft_id: str, path: str, extension_point: str, code: str) -> dict:
        ep = EXTENSION_POINTS.get(extension_point)
        if ep is None or "component" not in ep["kinds"]:
            raise SimlabError("E_EXTENSION_POINT", f"{extension_point!r} is not a component extension point "
                              f"({sorted(k for k, v in EXTENSION_POINTS.items() if 'component' in v['kinds'])})", "/extension_point")
        try:
            tree = ast.parse(code, filename=path)
        except SyntaxError as exc:
            raise SimlabError("E_EXTENSION_POINT", f"component code does not parse: {exc}", "/code") from None
        names = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
        if ep["entry"] not in names:
            raise SimlabError("E_EXTENSION_POINT", f"{extension_point} component must define {ep['entry']}()", "/code")
        return self._put(draft_id, path, "component", code.encode(), extension_point)

    def artifact_list(self, draft_id: str) -> dict:
        row = self._draft(draft_id, writable=False)
        arts = [dict(r) for r in self.store.q(
            "SELECT path,kind,extension_point,sha256,bytes FROM draft_artifacts WHERE draft_id=? ORDER BY path", (draft_id,))]
        return {"draft_id": draft_id, "bound_manifest_id": row["bound_manifest_id"],
                "bound_experiment_id": row["bound_experiment_id"], "header": json.loads(row["header"]),
                "parent": json.loads(row["parent"]) if row["parent"] else None, "artifacts": arts}

    def artifact_get(self, draft_id: str, path: str) -> dict:
        self._draft(draft_id, writable=False)
        row = self.store.q1("SELECT kind,sha256,bytes FROM draft_artifacts WHERE draft_id=? AND path=?", (draft_id, path))
        if row is None:
            raise SimlabError("E_SEMANTIC_UNKNOWN_REF", f"draft {draft_id} has no artifact {path}", "/path")
        data = self._file(draft_id, path)
        try:
            return {"path": path, "kind": row["kind"], "sha256": row["sha256"], "content": data.decode()}
        except UnicodeDecodeError:
            return {"path": path, "kind": row["kind"], "sha256": row["sha256"], "content_b64": base64.b64encode(data).decode()}

    def artifact_delete(self, draft_id: str, path: str) -> dict:
        self._draft(draft_id)
        with self.store.tx() as db:
            n = db.execute("DELETE FROM draft_artifacts WHERE draft_id=? AND path=?", (draft_id, check_path(path))).rowcount
        if not n:
            raise SimlabError("E_SEMANTIC_UNKNOWN_REF", f"draft {draft_id} has no artifact {path}", "/path")
        (self.store.drafts_dir / draft_id / path).unlink(missing_ok=True)
        return {"draft_id": draft_id, "deleted": path}

    # bind -----------------------------------------------------------
    def assemble(self, draft_id: str, header: dict | None) -> tuple[dict, list[dict], dict[str, bytes]]:
        row = self._draft(draft_id, writable=False)
        base = json.loads(row["header"])
        if header:
            unknown = set(header) - HEADER_FIELDS
            if unknown:
                raise SimlabError("E_INVALID_INPUT", f"unknown header fields: {sorted(unknown)}", "/header")
            base.update(header)
        if row["parent"] and "parent" not in base:
            base["parent"] = json.loads(row["parent"])
        arts = [dict(r) for r in self.store.q("SELECT * FROM draft_artifacts WHERE draft_id=? ORDER BY path", (draft_id,))]
        files = {a["path"]: self._file(draft_id, a["path"]) for a in arts}
        exp = {"record": "simlab-experiment", "schema_version": SCHEMA_VERSION, **base}
        # Structured artifacts become experiment fields (the artifacts stay in the manifest too).
        if "procedure.json" in files:
            exp["procedure"] = json.loads(files["procedure.json"])
        ivs = [json.loads(files[a["path"]]) for a in arts if a["kind"] == "intervention"]
        if ivs:
            proc = dict(exp.get("procedure") or {"steps": []})
            declared = {i.get("intervention_id") for i in ivs}
            proc["interventions"] = [i for i in proc.get("interventions", []) if i.get("intervention_id") not in declared] + ivs
            exp["procedure"] = proc
        ms = [json.loads(files[a["path"]]) for a in arts if a["kind"] == "measurement"]
        if ms:
            declared = {m.get("measurement_id") for m in ms}
            exp["measurements"] = [m for m in exp.get("measurements", []) if m.get("measurement_id") not in declared] + ms
        for folder, field in (("observations/", "trace_signals"), ("probes/", "probes")):
            obs = [json.loads(files[a["path"]]) for a in arts if a["kind"] == "observation" and a["path"].startswith(folder)]
            if obs:
                declared = {o.get("signal") for o in obs}
                exp[field] = [o for o in exp.get(field, []) if o.get("signal") not in declared] + obs
        manifest_artifacts = [{"path": a["path"], "kind": a["kind"], "sha256": a["sha256"], "bytes": a["bytes"],
                               **({"extension_point": a["extension_point"]} if a["extension_point"] else {})} for a in arts]
        return exp, manifest_artifacts, files

    def bind(self, draft_id: str, header: dict | None = None) -> dict:
        self._draft(draft_id)
        exp, manifest_artifacts, files = self.assemble(draft_id, header)
        bindings = sorted({(c.get("extension_point"), c.get("artifact")) for arm in exp.get("arms", []) or []
                           for c in (arm.get("components") or []) if isinstance(c, dict)}, key=lambda x: (str(x[0]), str(x[1])))
        experiment_id = experiment_id_for(exp, manifest_artifacts)
        manifest = {"record": "simlab-manifest", "schema_version": SCHEMA_VERSION, "experiment_id": experiment_id,
                    "artifacts": manifest_artifacts,
                    "extension_bindings": [{"extension_point": str(e), "artifact": str(p)} for e, p in bindings]}
        msha = sha256_hex(manifest)
        manifest = {**manifest, "manifest_id": "man-" + msha[:24], "manifest_sha256": msha}
        for path, data in files.items():
            self.store.put_blob(data)
        self.store.put_manifest(manifest)
        exp = {**exp, "experiment_id": experiment_id,
               "assets": {"manifest_id": manifest["manifest_id"], "manifest_sha256": msha}}
        with self.store.tx() as db:
            db.execute("UPDATE drafts SET bound_manifest_id=?, bound_experiment_id=?, updated_at=? WHERE draft_id=?",
                       (manifest["manifest_id"], experiment_id, now(), draft_id))
        return {"experiment": exp, "manifest": manifest}


def experiment_id_for(experiment: dict, manifest_artifacts: list[dict]) -> str:
    """Content identity of an experiment: everything except its ID and asset reference, plus every artifact hash."""
    from simlab.contracts.records import Experiment  # noqa: PLC0415

    body = {k: v for k, v in experiment.items() if k not in {"experiment_id", "assets"}}
    try:  # normalized form, so explicit defaults and omitted defaults give the same identity
        body = Experiment.model_validate({**body, "assets": None}).model_dump(mode="json", exclude={"experiment_id", "assets"})
    except Exception:  # an invalid experiment still gets a stable identity; validation reports why it is invalid
        pass
    arts = sorted(({"path": a["path"], "sha256": a["sha256"], "kind": a["kind"]} for a in manifest_artifacts),
                  key=lambda a: a["path"])
    return "exp-" + sha256_hex({"experiment": body, "artifacts": arts})[:24]
